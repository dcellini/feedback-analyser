
import { z } from "zod";

/**
 * CHAPTER 7 — STEP 3B: NUMERICAL VERIFICATION
 *
 * NEW FILE
 *
 * PURPOSE:
 * Verify structured numerical claims against
 * trusted statistics returned by our tools.
 *
 * WHY?
 * An LLM can retrieve the correct statistics
 * and still report the wrong numbers.
 *
 * We therefore compare numbers in application
 * code instead of asking the LLM to verify itself.
 */

/**
 * The metrics our verifier currently understands.
 *
 * We start with totalFeedback because it is
 * already available from getFeedbackStats.
 */
export const numericalMetricSchema = z.enum([
  "totalFeedback",
]);

/**
 * Supported comparison operators.
 *
 * eq = equals
 * gt = greater than
 * gte = greater than or equal to
 * lt = less than
 * lte = less than or equal to
 */
export const numericalOperatorSchema = z.enum([
  "eq",
  "gt",
  "gte",
  "lt",
  "lte",
]);

/**
 * A numerical claim is structured data.
 *
 * Example:
 *
 * {
 *   text: "There were 42 feedback submissions.",
 *   metric: "totalFeedback",
 *   operator: "eq",
 *   value: 42
 * }
 *
 * The text is for display.
 * The other fields are used for verification.
 */
export const numericalClaimSchema = z.strictObject({
  text: z.string().min(1),

  metric: numericalMetricSchema,

  operator: numericalOperatorSchema,

  value: z.number().finite(),
});

export type NumericalClaim = z.infer<
  typeof numericalClaimSchema
>;

/**
 * Trusted statistics are supplied by our
 * application, not generated by Gemini.
 */
export type TrustedFeedbackStats = {
  totalFeedback: number;
};

/**
 * A discriminated union makes verification
 * success and failure explicit.
 */
export type NumericalVerificationResult =
  | { valid: true }
  | {
      valid: false;
      reason: string;
    };

/**
 * Verify a numerical claim.
 *
 * stats is unknown because tool results should
 * be validated at runtime before we trust them.
 */
export const verifyNumericalClaim = (
  claim: unknown,
  stats: unknown,
): NumericalVerificationResult => {
  /**
   * STEP 1 — Validate the model-generated claim.
   */
  const parsedClaim = numericalClaimSchema.safeParse(
    claim,
  );

  if (!parsedClaim.success) {
    return {
      valid: false,
      reason: "Invalid numerical claim structure.",
    };
  }

  /**
   * STEP 2 — Validate the trusted statistics.
   *
   * We do not accept missing or malformed stats.
   *
   * totalFeedback must be a non-negative integer.
   */
  const statsSchema = z.strictObject({
    totalFeedback: z.number().int().nonnegative(),
  });

  const parsedStats = statsSchema.safeParse(stats);

  if (!parsedStats.success) {
    return {
      valid: false,
      reason: "Trusted statistics are missing or invalid.",
    };
  }

  const { metric, operator, value } = parsedClaim.data;

  const actualValue = parsedStats.data[metric];

  /**
   * STEP 3 — Perform the comparison.
   *
   * This is ordinary TypeScript logic.
   * No LLM is involved.
   */
  let matches = false;

  switch (operator) {
    case "eq":
      matches = actualValue === value;
      break;

    case "gt":
      matches = actualValue > value;
      break;

    case "gte":
      matches = actualValue >= value;
      break;

    case "lt":
      matches = actualValue < value;
      break;

    case "lte":
      matches = actualValue <= value;
      break;
  }

  /**
   * STEP 4 — Reject incorrect numerical claims.
   */
  if (!matches) {
    return {
      valid: false,
      reason:
        `Numerical claim failed: ${metric} ` +
        `${operator} ${value} ` +
        `(actual value: ${actualValue}).`,
    };
  }

  return { valid: true };
};
