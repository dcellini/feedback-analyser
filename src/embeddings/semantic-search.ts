import type { EmbeddingProvider } from "./embedding-provider.js";
import { cosineSimilarity } from "./internal/cosine-similarity.js";
import type { EmbeddedFeedback } from "./prepare-feedback.js";

/**
 * One employee feedback response that we want to search.
 *
 * Example:
 * { id: "1", text: "My manager ignores my concerns." }
 */
export interface SearchableFeedback {
  id: string;
  text: string;
}

/**
 * A search result contains the original feedback and
 * a score indicating its similarity to the search query.
 */
export interface SearchResult extends SearchableFeedback {
  similarity: number;
}


/**
 * SEMANTIC SEARCH USING PREPARED FEEDBACK
 *
 * Feedback embeddings have already been generated by
 * prepareFeedback(), so we don't regenerate them.
 *
 * Example:
 *
 * query = "Problems with leadership"
 *
 * preparedFeedback = [
 *   {
 *     id: "1",
 *     text: "My manager ignores my concerns.",
 *     embedding: [0.9, 0.1]
 *   },
 *   {
 *     id: "2",
 *     text: "The office needs better parking.",
 *     embedding: [0, 1]
 *   }
 * ]
 *
 * The only new embedding we generate is for the search query.
 */
export const semanticSearch = async ({
  query,
  feedback,
  embeddingProvider,
  limit = 5,
}: {
  query: string;
  feedback: readonly EmbeddedFeedback[];
  embeddingProvider: EmbeddingProvider;
  limit?: number;
}): Promise<SearchResult[]> => {
  /**
   * STEP 1 — EMBED THE QUERY
   *
   * Example:
   * "Problems with leadership" → [1, 0]
   *
   * This is the only embedding request during a search.
   */
  const queryEmbedding = await embeddingProvider.embed(query);

  /**
   * STEP 2 — COMPARE AGAINST STORED EMBEDDINGS
   *
   * No API calls are needed here.
   *
   * We already have the vectors for every feedback response.
   *
   * Example:
   *   query    = [1, 0]
   *   feedback = [0.9, 0.1]
   *
   * cosineSimilarity(...) ≈ 0.994
   */
  const results: SearchResult[] = feedback.map((item) => ({
    id: item.id,
    text: item.text,
    similarity: cosineSimilarity(queryEmbedding, item.embedding),
  }));

  /**
   * STEP 3 — RANK AND LIMIT
   *
   * Sort highest similarity first.
   *
   * Example:
   *   Before: [0.15, 0.94, 0.88]
   *   After:  [0.94, 0.88, 0.15]
   *
   * Return the first 'limit' results.
   */
  return results
    .sort((a, b) => b.similarity - a.similarity)
    .slice(0, limit);
};
